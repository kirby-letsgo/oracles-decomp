// The two non-ASCII glyphs the menus use out of the ROM font.
static const char *const heart_art =
  "........" ".##.##.." "#######." "#######." ".#####.." "..###..." "...#...." "........";
static const char *const cursor_art =
  "..#....." "..##...." "..###..." "..####.." "..###..." "..##...." "..#....." "........";

// Ink is a clear bit in the UI font's rows, so a blank row is 0xff.
static void blit(UiFont *font, uint8_t ch, const char *rows) {
  for (int r = 0; r < GLYPH_ROWS; r++) {
    uint8_t bits = 0xff;
    for (int b = 0; b < UI_GLYPH_W; b++)
      if (rows[r * UI_GLYPH_W + b] == '#') bits &= (uint8_t)~(0x80 >> b);
    font->glyph[ch][GLYPH_TOP + r] = bits;
  }
}

void ui_font_builtin(UiFont *font) {
  memset(font->glyph, 0xff, sizeof font->glyph);
  for (size_t i = 0; i < sizeof art / sizeof art[0]; i++) blit(font, (uint8_t)(' ' + i), art[i]);
  blit(font, UI_CH_HEART, heart_art);
  blit(font, UI_CH_CURSOR, cursor_art);
  font->loaded = true;
}
