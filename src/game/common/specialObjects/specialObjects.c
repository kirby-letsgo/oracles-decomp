  CYC(0x40d2, 0x40d3); alu_rlca(gb);
  CYC(0x40d3, 0x40d4); alu_or(gb, B);
  CYC(0x40d4, 0x40d5); B = A;
  CYC(0x40d5, 0x40d7); A = 0x0f;
  CYC(0x40d7, 0x40d8); alu_and(gb, C);
  CYC(0x40d8, 0x40d9); alu_or(gb, B);
