  CYC(0x40c6, 0x40c7); alu_xor(gb, A);
  CYC(0x40c7, 0x40ca); mem_wr(gb, 0xcbc3, A);
  CYC(0x40ca, 0x40cc); A = 0xa0;
  CYC(0x40cc, 0x40cd); alu_and(gb, C);
  CYC(0x40cd, 0x40ce); alu_rrca(gb);
