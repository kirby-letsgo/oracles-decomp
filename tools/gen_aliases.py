#!/usr/bin/env python3
"""Write src/hooks/alias_seasons.sym: Seasons addresses under the Ages spelling of labels the two
symbol files name differently but unambiguously, case aside (a plain Ages label that Seasons keeps as the
@local of one routine, and the reverse).

usage: tools/gen_aliases.py
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from symfiles import rom_labels

al, sl = rom_labels('ref/oracles-disasm/ages.sym'), rom_labels('ref/oracles-disasm/seasons.sym', extras=False)
by_suffix = {}
for n in sl:
    if '@' in n: by_suffix.setdefault(n.split('@', 1)[1].lower(), []).append(n)
out = []
for n in sorted(al):
    if n in sl or '@' in n: continue
    c = by_suffix.get(n.lower())
    if c and len(c) == 1 and len(sl[c[0]]) == 1: out.append((sl[c[0]][0], n, c[0]))
ages_by_suffix = {}
for n in al:
    if '@' in n: ages_by_suffix.setdefault(n.split('@', 1)[1].lower(), []).append(n)
for n in sorted(sl):
    if n in al or '@' in n or len(sl[n]) != 1: continue
    c = ages_by_suffix.get(n.lower())
    if c and len(c) == 1 and c[0] not in sl: out.append((sl[n][0], c[0], n))
with open('src/hooks/alias_seasons.sym', 'w') as f:
    f.write('# generated by tools/gen_aliases.py; do not edit: Seasons addresses under the Ages spelling\n')
    for (b, a), name, sname in out: f.write(f'{b:02x}:{a:04x} {name}   # {sname}\n')
print(f'{len(out)} aliases')
