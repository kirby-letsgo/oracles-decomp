#!/usr/bin/env python3
"""Generate src/hooks/table.h from the disassembly symbol file and the list of ported routines.

usage: tools/gen_hooks.py [ref/oracles-disasm/ages.sym] [src/hooks/ported.txt] [src/hooks/table.h]
ported.txt: one routine name per line, '#' comments allowed.
"""
import re, sys
sym = sys.argv[1] if len(sys.argv) > 1 else 'ref/oracles-disasm/ages.sym'
ported = sys.argv[2] if len(sys.argv) > 2 else 'src/hooks/ported.txt'
out = sys.argv[3] if len(sys.argv) > 3 else 'src/hooks/table.h'
labels = {}
in_labels = False
for line in open(sym):
    line = line.strip()
    if line.startswith('['):
        in_labels = line == '[labels]'
        continue
    if not in_labels or not line:
        continue
    m = re.match(r'([0-9a-f]{2}):([0-9a-f]{4}) (\S+)$', line)
    if m:
        labels.setdefault(m.group(3), (int(m.group(1), 16), int(m.group(2), 16)))
names = [l.split('#')[0].strip() for l in open(ported)]
names = [n for n in names if n]
rows = []
for n in names:
    if n not in labels:
        sys.exit(f'unknown routine {n}')
    bank, addr = labels[n]
    if addr >= 0x8000:
        sys.exit(f'{n} is not in ROM ({bank:02x}:{addr:04x})')
    rows.append((addr, bank, n))
rows.sort()
with open(out, 'w') as f:
    f.write('// generated by tools/gen_hooks.py from %s; do not edit\n' % sym)
    for addr, bank, n in rows:
        f.write('HOOK(0x%02x, 0x%04x, %s)\n' % (bank, addr, n))
total = sum(1 for n, (b, a) in labels.items() if a < 0x8000 and not n.startswith('@') and '.' not in n)
print('%d routines hooked, %d ROM labels in symbol file' % (len(rows), total))
