#!/usr/bin/env python3
"""Classify the labels of a symbol file as code or data from the disassembly sources.

usage: tools/label_kinds.py seasons.sym [src/hooks/seasons_code_labels.txt]
A label is code when it sits in code/ or object_code/ and the first directive after it is an
instruction (or one of the disassembly's call/jump macros); `.db`, `.dw`, `.incbin`, script
and data macros, and every label of the data trees, make it data. Labels only the symbol file has
(no source line, such as the resume points) are left out and decided elsewhere.
"""
import glob, os, re, sys

sym = sys.argv[1]
out = sys.argv[2] if len(sys.argv) > 2 else 'src/hooks/seasons_code_labels.txt'
names = set()
for line in open(sym):
    m = re.match(r'[0-9a-f]{2}:([0-9a-f]{4}) (\S+)$', line.strip())
    if m and int(m.group(1), 16) < 0x8000 and '@' not in m.group(2): names.add(m.group(2))
MNEMONICS = {'ld', 'ldh', 'ldi', 'ldd', 'push', 'pop', 'call', 'jp', 'jr', 'ret', 'reti', 'rst', 'nop', 'halt', 'stop', 'di', 'ei',
             'add', 'adc', 'sub', 'sbc', 'and', 'or', 'xor', 'cp', 'inc', 'dec', 'daa', 'cpl', 'scf', 'ccf',
             'rlca', 'rrca', 'rla', 'rra', 'rlc', 'rrc', 'rl', 'rr', 'sla', 'sra', 'swap', 'srl', 'bit', 'set', 'res'}
kinds = {}
for path in glob.glob('ref/oracles-disasm/**/*.s', recursive=True):
    lines = open(path, errors='replace').read().split('\n')
    for i, l in enumerate(lines):
        m = re.match(r'^([A-Za-z_][A-Za-z0-9_.]*):', l)
        if not m or m.group(1) not in names: continue
        j = i + 1
        while j < len(lines) and (not lines[j].strip() or lines[j].strip().startswith(';') or re.match(r'^\s*\.(ifdef|else|endif|ifndef|if\b)', lines[j]) or re.match(r'^[@A-Za-z_][A-Za-z0-9_@]*:\s*$', lines[j].strip())): j += 1
        if j >= len(lines): continue
        first = lines[j].strip().split(';')[0].strip()
        if not first: continue
        word = re.split(r'[\s,]', first)[0].lower()
        in_code_dir = '/code/' in path or '/object_code/' in path or path.endswith('scriptHelper.s')
        code = in_code_dir and (word in MNEMONICS or word in ('jpab', 'callab', 'jpba', 'callba', 'callhl', 'ldbc', 'ldde', 'ldhl', 'setrombank', 'callfrombank0', 'rst_jumptable', 'rst_addatohl', 'rst_adddoubleindex'))
        # a data directive or macro wins over an instruction seen earlier in another file
        kinds[m.group(1)] = code if m.group(1) not in kinds else (kinds[m.group(1)] and code)
with open(out, 'w') as f:
    f.write('# generated by tools/label_kinds.py; do not edit: labels whose source line is an instruction\n')
    for n in sorted(n for n, c in kinds.items() if c): f.write(n + '\n')
print(f'{sum(1 for c in kinds.values() if c)} code, {sum(1 for c in kinds.values() if not c)} data, {len(names) - len(kinds)} without a source line')
