#!/usr/bin/env python3
"""Generate src/game/ram.h (named WRAM/HRAM addresses) from the disassembly symbol files.

usage: tools/gen_ram.py [ages.sym] [seasons.sym] [src/hooks/generated.txt] [src/game/ram.h]
Labels that are code (present in generated.txt) are left out so they do not clash with functions.
A name whose address differs between the games becomes a RAMSYM() lookup into the running game's
table (src/game/syms.c, generated by tools/gen_syms.py from src/hooks/ram_syms.txt).
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from symfiles import ram_map

ages_sym = sys.argv[1] if len(sys.argv) > 1 else 'ref/oracles-disasm/ages.sym'
seasons_sym = sys.argv[2] if len(sys.argv) > 2 else 'ref/oracles-disasm/seasons.sym'
generated = sys.argv[3] if len(sys.argv) > 3 else 'src/hooks/generated.txt'
out = sys.argv[4] if len(sys.argv) > 4 else 'src/game/ram.h'
ages = ram_map(ages_sym, generated)
seasons = ram_map(seasons_sym, generated)
differs = {}
with open(out, 'w') as f:
    f.write('// generated by tools/gen_ram.py from %s and %s; do not edit\n#pragma once\n' % (ages_sym, seasons_sym))
    f.write('#include "game/syms.h"\n')
    f.write('#define W8(n) (gb->wram[n##_BANK][(n) & 0xfff])\n')
    f.write('#define WP(n) (&gb->wram[n##_BANK][(n) & 0xfff])\n')
    f.write('#define H8(n) (gb->hram[(n) - 0xff80])\n')
    f.write('#define HP(n) (&gb->hram[(n) - 0xff80])\n')
    for cn, (bank, addr) in sorted(ages.items(), key=lambda kv: (kv[1][1], kv[0])):
        s = seasons.get(cn)
        if s is not None and s != (bank, addr):
            f.write('#define %s RAMSYM(R_%s)\n' % (cn, cn))
            if addr < 0xe000: f.write('#define %s_BANK RAMBANK(R_%s)\n' % (cn, cn))
            differs[cn] = (bank, addr, s[0], s[1])
        else:
            f.write('#define %s 0x%04x\n' % (cn, addr))
            if addr < 0xe000: f.write('#define %s_BANK %d\n' % (cn, bank))
with open('src/hooks/ram_syms.txt', 'w') as f:
    for cn, (ab, aa, sb, sa) in sorted(differs.items(), key=lambda kv: kv[1]):
        f.write('%s %d:%04x %d:%04x\n' % (cn, ab, aa, sb, sa))
print('%d RAM labels, %d differ between games' % (len(ages), len(differs)))
